export function getPublishedBlogArticles() {
  return BLOG_ARTICLES.filter((a) => a.status === 'PUBLISHED');
}

/**
 * Helper to get a blog article by slug (supports primary slugs and legacy aliases)
 */
export function getBlogArticleBySlug(slug) {
  if (!slug) return null;
  const normalized = String(slug).trim().toLowerCase();
  
  return BLOG_ARTICLES.find(
    (a) =>
      (a.slug === normalized || (a.aliases && a.aliases.includes(normalized))) &&
      a.status === 'PUBLISHED'
  ) || null;
}

/**
 * Helper to get all categories
 */
export function getAllBlogCategories() {
  return BLOG_CATEGORIES;
}

/**
 * Helper to get related articles for a given article
 */
export function getRelatedArticles(article, limit = 3) {
  if (!article) return [];
  
  // 1. Explicitly mapped related articles
  if (article.relatedArticles && article.relatedArticles.length > 0) {
    const resolved = article.relatedArticles
      .map((slug) => getBlogArticleBySlug(slug))
      .filter(Boolean);
    if (resolved.length >= limit) {
      return resolved.slice(0, limit);
    }
  }

  // 2. Fallback to same category / cluster
  const pool = BLOG_ARTICLES.filter(
    (a) => a.slug !== article.slug && a.status === 'PUBLISHED' && (a.category === article.category || a.cluster === article.cluster)
  );

  return pool.slice(0, limit);
}
