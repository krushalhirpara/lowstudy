async function seed() {
  console.log('🌱 Seeding & Upserting Verified Gujarat Law Colleges...\n');

  // 1. Correct Anand Law College: Flag as SPU affiliation, remove from GU selectable list
  await prisma.college.updateMany({
    where: { id: 'col-anand-law' },
    data: {
      status: 'PENDING_REVIEW',
      sourceUrl: 'Affiliated with Sardar Patel University (SPU), not Gujarat University',
    }
  });
  console.log('  ⚠️ Updated col-anand-law status to PENDING_REVIEW (affiliated with SPU, not GU)');

  // 2. Upsert all verified colleges
  let upsertedCount = 0;
  for (const c of VERIFIED_COLLEGES_DATA) {
    await prisma.college.upsert({
      where: { id: c.id },
      update: {
        universityId: c.universityId,
        name: c.name,
        city: c.city,
        district: c.district,
        type: c.type,
        officialWebsite: c.officialWebsite,
        sourceUrl: c.sourceUrl,
        programsJson: c.programsJson,
        status: c.status,
        hasSeparateSyllabus: c.hasSeparateSyllabus,
      },
      create: {
        id: c.id,
        universityId: c.universityId,
        name: c.name,
        city: c.city,
        district: c.district,
        type: c.type,
        officialWebsite: c.officialWebsite,
        sourceUrl: c.sourceUrl,
        programsJson: c.programsJson,
        status: c.status,
        hasSeparateSyllabus: c.hasSeparateSyllabus,
      }
    });
    upsertedCount++;
    console.log(`  ✅ Upserted [${c.id}] ${c.name} (${c.universityId})`);
  }

  console.log(`\n🎉 Successfully processed ${upsertedCount} verified law college records.`);
  process.exit(0);
}

seed().catch(err => {
  console.error('Seeding failed:', err);
  process.exit(1);
});
